/**
 * Resolves comprehensive editorial content and educational guides for any category slug or name.
 */
export function getCategoryRichContent(slugOrName?: string): CategoryGuide | null {
  if (!slugOrName) return null;

  const raw = slugOrName.trim();
  const decoded = decodeURIComponent(raw).toLowerCase().trim();
  const cleaned = decoded.replace(/\s+/g, '-');

  // 1. Direct key match
  if (CATEGORY_GUIDES[raw]) return CATEGORY_GUIDES[raw];
  if (CATEGORY_GUIDES[decoded]) return CATEGORY_GUIDES[decoded];
  if (CATEGORY_GUIDES[cleaned]) return CATEGORY_GUIDES[cleaned];

  // 2. Alias resolution
  const targetKey = SLUG_ALIASES[raw] || SLUG_ALIASES[decoded] || SLUG_ALIASES[cleaned];
  if (targetKey && CATEGORY_GUIDES[targetKey]) {
    return CATEGORY_GUIDES[targetKey];
  }

  // 3. Substring / fuzzy match against known categories
  for (const [alias, canonicalKey] of Object.entries(SLUG_ALIASES)) {
    if (decoded.includes(alias) || alias.includes(decoded)) {
      if (CATEGORY_GUIDES[canonicalKey]) {
        return CATEGORY_GUIDES[canonicalKey];
      }
    }
  }

  // Fallback to general Oud guide if nothing matches but represents store specialties
  return CATEGORY_GUIDES['oud'] || null;
}
